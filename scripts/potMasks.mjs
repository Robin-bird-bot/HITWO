// Turns Cracked Pots' pictures (assets/minigames/cracked-pots/pot-1.png to
// pot-3.png) into src/minigames/crackedPots/masks.ts: for each pot, which
// pixels are pot (alpha over half), as spans per row. The game's logic stays
// pure (no canvas): it cuts the shards from these masks.
//
// Run it again after changing the art:  node scripts/potMasks.mjs
// It reads 8-bit RGBA PNGs (no interlacing), which is what the art is.
import { readFileSync, writeFileSync } from 'node:fs';
import { inflateSync } from 'node:zlib';

const FILES = [1, 2, 3].map((n) => `assets/minigames/cracked-pots/pot-${n}.png`);
const OUT = 'src/minigames/crackedPots/masks.ts';

function decode(file) {
  const buf = readFileSync(file);
  let at = 8;
  let width = 0;
  let height = 0;
  const idat = [];
  while (at < buf.length) {
    const len = buf.readUInt32BE(at);
    const type = buf.toString('ascii', at + 4, at + 8);
    const data = buf.subarray(at + 8, at + 8 + len);
    if (type === 'IHDR') {
      width = data.readUInt32BE(0);
      height = data.readUInt32BE(4);
      const [depth, color, , , interlace] = data.subarray(8, 13);
      if (depth !== 8 || color !== 6 || interlace !== 0)
        throw new Error(`${file}: expected 8-bit RGBA, not interlaced`);
    }
    if (type === 'IDAT') idat.push(data);
    at += 12 + len;
  }
  const raw = inflateSync(Buffer.concat(idat));
  const bpp = 4;
  const stride = width * bpp;
  const px = Buffer.alloc(height * stride);
  for (let y = 0; y < height; y++) {
    const filter = raw[y * (stride + 1)];
    const line = raw.subarray(y * (stride + 1) + 1, (y + 1) * (stride + 1));
    for (let x = 0; x < stride; x++) {
      const a = x >= bpp ? px[y * stride + x - bpp] : 0;
      const b = y > 0 ? px[(y - 1) * stride + x] : 0;
      const c = x >= bpp && y > 0 ? px[(y - 1) * stride + x - bpp] : 0;
      let v = line[x];
      if (filter === 1) v += a;
      else if (filter === 2) v += b;
      else if (filter === 3) v += Math.floor((a + b) / 2);
      else if (filter === 4) {
        const p = a + b - c;
        const pa = Math.abs(p - a);
        const pb = Math.abs(p - b);
        const pc = Math.abs(p - c);
        v += pa <= pb && pa <= pc ? a : pb <= pc ? b : c;
      }
      px[y * stride + x] = v & 255;
    }
  }
  return { width, height, alpha: (x, y) => px[y * stride + x * bpp + 3] };
}

const pots = FILES.map((file) => {
  const img = decode(file);
  const rows = [];
  for (let y = 0; y < img.height; y++) {
    const spans = [];
    let start = -1;
    for (let x = 0; x <= img.width; x++) {
      const on = x < img.width && img.alpha(x, y) > 127;
      if (on && start < 0) start = x;
      if (!on && start >= 0) {
        spans.push([start, x]);
        start = -1;
      }
    }
    rows.push(spans);
  }
  return { file: file.split('/').pop(), width: img.width, height: img.height, rows };
});

const body = pots
  .map(
    (p) =>
      `  {\n    file: '${p.file}',\n    width: ${p.width},\n    height: ${p.height},\n    rows: ${JSON.stringify(p.rows)},\n  },`,
  )
  .join('\n');

writeFileSync(
  OUT,
  `/**
 * Cracked Pots' pot shapes (generated by scripts/potMasks.mjs from
 * assets/minigames/cracked-pots/pot-1.png to pot-3.png; don't edit by hand).
 * Each row lists its spans of pot pixels, [from, to) in x.
 */
export interface PotMask {
  file: string;
  width: number;
  height: number;
  rows: readonly (readonly (readonly [number, number])[])[];
}

export const POT_MASKS: readonly PotMask[] = [
${body}
];
`,
);
console.log(`Wrote ${OUT}: ${pots.map((p) => `${p.file} ${p.width}×${p.height}`).join(', ')}`);
