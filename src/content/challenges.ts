/**
 * Every challenge, Trial and opportunity, as data. The source of truth is
 * docs/design/04-challenges.md: names, tiers, nodes, who pays, costs,
 * penalties and [bracket] ranges are copied from it.
 *
 * - Card text drops [brackets] (game logic) and shows {names} as the rolled
 *   numbers. A Y shows as its range on the card, and as each hiker's own
 *   number in their section.
 * - Descriptions are "…" until Wyatt writes them (descriptionPlaceholder).
 * - The 4 opportunities are made up so the blue flow works (placeholder).
 */
import type {
  Amount,
  CardDef,
  ChallengeDef,
  CostOption,
  Effect,
  Requirement,
  ResourceFilter,
  RollDef,
  TrialDef,
} from '../engine/challenges/types';
import type { ItemType } from '../engine/effects';
import type { NodeType, StatName } from '../engine/types';

// ── Little builders, so each card reads close to the doc ────────────────────

const F: NodeType = 'forest';
const R: NodeType = 'river';
const W: NodeType = 'wildlife';
const M: NodeType = 'mountain';

const X = (min: number, max: number, reverse = false): RollDef => ({
  roll: 'x',
  range: [min, max],
  ...(reverse ? { reverse: true as const } : {}),
});
const Y = (min: number, max: number): RollDef => ({ roll: 'y', range: [min, max] });

const nodesOf = (...nodes: NodeType[]): ResourceFilter => ({ nodes });
const idsOf = (...ids: string[]): ResourceFilter => ({ ids });

const res = (
  count: Amount,
  filter?: ResourceFilter,
  extra: Partial<Extract<Requirement, { kind: 'resources' }>> = {},
): Requirement => ({ kind: 'resources', count, ...(filter ? { filter } : {}), ...extra });
const items = (count: Amount, ...itemTypes: ItemType[]): Requirement => ({
  kind: 'items',
  count,
  ...(itemTypes.length ? { itemTypes } : {}),
});
const caps = (count: Amount): Requirement => ({ kind: 'caps', count });
const stat = (count: Amount, ...stats: StatName[]): Requirement => ({ kind: 'stat', stats, count });
const durability = (count: Amount, extra: { slot?: 'gear'; oneItem?: true } = {}): Requirement => ({
  kind: 'durability',
  count,
  ...extra,
});

type Unit = 'phases' | 'days' | 'nights';
const cond = (id: string, duration: Amount, unit: Unit, extra: Partial<Effect> = {}): Effect =>
  ({ op: 'condition', id, duration, unit, ...extra }) as Effect;
const injury = (extra: Partial<Effect> = {}): Effect => ({ op: 'injury', ...extra }) as Effect;
const lose = (s: StatName, n: Amount, extra: Partial<Effect> = {}): Effect =>
  ({ op: 'stat', stat: s, delta: n, lose: true, ...extra }) as Effect;

const DESCRIPTION = '…';

type ChallengeInput = Omit<ChallengeDef, 'id' | 'kind' | 'description' | 'art'> & {
  kind?: 'challenge' | 'opportunity';
  art?: boolean;
};
type TrialInput = Omit<TrialDef, 'id' | 'kind' | 'description' | 'art'> & { art?: boolean };

/** "Bear With a Gun!!" → "bear-with-a-gun": the id, and the art's file name. */
export function slug(name: string): string {
  return name
    .toLowerCase()
    .replace(/['’]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

function ch(input: ChallengeInput): ChallengeDef {
  return {
    kind: 'challenge',
    art: false,
    ...input,
    id: slug(input.name),
    description: DESCRIPTION,
    descriptionPlaceholder: true,
  } as ChallengeDef;
}

function trial(input: TrialInput): TrialDef {
  return {
    art: false,
    ...input,
    id: slug(input.name),
    kind: 'trial',
    description: DESCRIPTION,
    descriptionPlaceholder: true,
  } as TrialDef;
}

